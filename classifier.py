import math
from preprocessor import tokenize_text


class NaiveBayesClassifier:
    """
    Реализация мультинормального Наивного Байеса для классификации текста.
    Использует логарифмические вероятности и сглаживание Лапласа.
    """
    
    def __init__(self, alpha=1.0):
        """
        Инициализация классификатора.
        
        Args:
            alpha (float): Параметр сглаживания Лапласа (по умолчанию 1.0)
        """
        self.alpha = alpha
        self.model = {}
        self.обучен = False
    
    def train(self, training_data, verbose=True):
        """
        Обучение модели на размеченных данных.
        
        Args:
            training_data (list): Список кортежей (текст, класс)
            verbose (bool): Выводить ли процесс обучения в консоль
            
        Returns:
            dict: Обученная модель
        """
        if verbose:
            print("\n" + "="*60)
            print(" ОБУЧЕНИЕ МОДЕЛИ НАИВНЫЙ БАЙЕС")
            print("="*60)
            print(f"Количество примеров: {len(training_data)}")
        
        # Инициализация счётчиков
        счётчик_классов = {}
        счётчик_слов = {}
        все_слова = set()
        
        # Шаг 1: Подсчёт частот классов и слов
        if verbose:
            print("\n[1/4] Подсчёт частот классов и слов...")
        
        for текст, класс in training_data:
            # Счётчик классов
            счётчик_классов[класс] = счётчик_классов.get(класс, 0) + 1
            
            # Инициализация счётчика слов для класса
            if класс not in счётчик_слов:
                счётчик_слов[класс] = {}
                if verbose:
                    print(f"  Добавлен класс: {класс}")
            
            # Токенизация и подсчёт слов
            токены = tokenize_text(текст)
            for слово in токены:
                все_слова.add(слово)
                счётчик_слов[класс][слово] = счётчик_слов[класс].get(слово, 0) + 1
        
        всего_примеров = len(training_data)
        размер_словаря = len(все_слова)
        
        if verbose:
            print(f"\n[2/4] Размер словаря: {размер_словаря} уникальных слов")
            print(f"  Всего примеров: {всего_примеров}")
            print(f"  Классы: {list(счётчик_классов.keys())}")
        
        # Шаг 2: Вычисление априорных вероятностей P(класс)
        if verbose:
            print("\n[3/4] Вычисление априорных вероятностей P(класс)...")
        
        log_prior = {}
        for класс, count in счётчик_классов.items():
            вероятность = count / всего_примеров
            log_prior[класс] = math.log(вероятность)
            if verbose:
                print(f"  P({класс}) = {вероятность:.3f}, log = {log_prior[класс]:.4f}")
        
        # Шаг 3: Вычисление условных вероятностей P(слово|класс)
        if verbose:
            print("\n[4/4] Вычисление условных вероятностей P(слово|класс) со сглаживанием...")
        
        log_likelihood = {}
        oov_prob = {}  # Вероятности для слов вне словаря (OOV - Out Of Vocabulary)
        
        for класс in счётчик_классов:
            сумма_слов = sum(счётчик_слов[класс].values())
            знаменатель = сумма_слов + self.alpha * размер_словаря
            
