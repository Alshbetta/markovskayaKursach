# -*- coding: utf-8 -*-
"""
preprocessor.py — Предобработка текста
Функции: токенизация, удаление стоп-слов
"""

СТОП_СЛОВА = {
    "и", "в", "на", "из", "с", "по", "для", "от", "к", "что", "это", "не",
    "все", "всех", "об", "о", "за", "при", "до", "или", "как", "а", "но",
    "же", "бы", "во", "со", "без", "под", "над", "через", "нет", "да",
    "у", "их", "ему", "ей", "им", "мне", "тебя", "себя", "твой", "свой",
}

def tokenize_text(text):
    токены = []
    for слово in text.lower().split():
        чистое = "".join(с for с in слово if с.isalpha())
        if чистое and len(чистое) > 2 and чистое not in СТОП_СЛОВА:
            токены.append(чистое)
    return токены

def preprocess_dataset(dataset):
    """
    Предварительная обработка всего датасета.
    
    Args:
        dataset (list): Список кортежей (текст, класс)
        
    Returns:
        list: Список кортежей (токены, класс)
    """
    обработанный = []
    for текст, класс in dataset:
        токены = tokenize_text(текст)
        обработанный.append((токены, класс))
    return обработанный